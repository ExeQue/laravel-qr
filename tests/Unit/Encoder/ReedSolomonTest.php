<?php

declare(strict_types=1);

namespace Tests\Unit\Encoder;

use ExeQue\Qr\Encoder\ReedSolomon;

covers(ReedSolomon::class);

pest()->group('encoding');

describe('reed-solomon', function (): void {
    // Hand-checked vectors: ISO/IEC 18004:2015 annex I ("01234567", 1-M) and Thonky's tutorial ("HELLO WORLD", 1-M).
    it('computes the error correction codewords', function (array $data, array $expected): void {
        expect(new ReedSolomon()->remainder($data, count($expected)))->toBe($expected);
    })->with([
        '01234567, 1-M' => [
            [0x10, 0x20, 0x0C, 0x56, 0x61, 0x80, 0xEC, 0x11, 0xEC, 0x11, 0xEC, 0x11, 0xEC, 0x11, 0xEC, 0x11],
            [0xA5, 0x24, 0xD4, 0xC1, 0xED, 0x36, 0xC7, 0x87, 0x2C, 0x55],
        ],
        'HELLO WORLD, 1-M' => [
            [0x20, 0x5B, 0x0B, 0x78, 0xD1, 0x72, 0xDC, 0x4D, 0x43, 0x40, 0xEC, 0x11, 0xEC, 0x11, 0xEC, 0x11],
            [0xC4, 0x23, 0x27, 0x77, 0xEB, 0xD7, 0xE7, 0xE2, 0x5D, 0x17],
        ],
    ]);

});
